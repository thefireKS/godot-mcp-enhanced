#!/usr/bin/env node
// scripts/gen-tool-docs.mjs
// 项目待办 :154 — 从 capability-matrix.json 生成 docs/tools/{name}.md 骨架文档。
// help 工具(help.ts:74-86)运行时读这些文档返回给 agent,故文档内容须准确(action/参数/层/安全级别)。
//
// 用法: node scripts/gen-tool-docs.mjs  (或 npm run gen:tool-docs)
// 原理: 读 docs/capability-matrix.json → 逐工具生成 markdown → 写 docs/tools/{name}.md
// 幂等: 同 matrix 输入产出相同输出,重跑 git diff=0

import { readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');
const MATRIX_PATH = join(repoRoot, 'docs', 'capability-matrix.json');
const OUT_DIR = join(repoRoot, 'docs', 'tools');

// ═══════════════════════════════════════════════════════════════════════════════
// 纯函数(可单测,不做 IO)
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * 推断工具所属层(headless/editor/bridge)。
 * needsEditor=true → editor; group 含 game/runtime → bridge; 其余 needsGodot → headless。
 */
export function inferLayer(tool) {
  if (tool.needsEditor === true) return 'editor';
  const g = (tool.group || '').toLowerCase();
  if (g === 'game' || g === 'bridge' || tool.name === 'game' || tool.name === 'runtime' || tool.name === 'runtime_assert') return 'bridge';
  return 'headless';
}

/**
 * 从 inputSchema 提取参数表行:[name, type, required, description]。
 * required 数组里的标 ✓,action 单独提为首个参数(若有)。
 */
export function extractParamRows(tool) {
  const props = tool.inputSchema?.properties || {};
  const required = new Set(tool.inputSchema?.required || tool.requiredParams || []);
  const rows = [];
  // action 排首位(若有)
  const actionProp = props.action;
  const otherKeys = Object.keys(props).filter(k => k !== 'action');
  const orderedKeys = actionProp ? ['action', ...otherKeys] : otherKeys;
  for (const name of orderedKeys) {
    const p = props[name] || {};
    // enum 类参数:action 值已在上方 Actions section 列出;其余 enum 超 3 项也只标 enum 不全列(避免长行)
    const enumCount = p.enum?.length || 0;
    const type = p.enum
      ? (name === 'action' || enumCount > 3 ? `enum (${enumCount} values)` : `enum: ${p.enum.join(' | ')}`)
      : (p.type || 'any');
    rows.push({
      name,
      type,
      required: required.has(name) ? '✓' : '',
      description: (p.description || '').replace(/\n/g, ' '),
    });
  }
  return rows;
}

/**
 * 生成单个工具的 markdown 文档骨架。
 * @param {object} tool capability-matrix 的单个 tool 对象
 * @param {string} matrixVersion capability-matrix.json 的 version 字段
 * @returns {string} markdown 文档内容
 */
export function generateToolDoc(tool, matrixVersion) {
  const layer = inferLayer(tool);
  const actions = tool.inputSchema?.properties?.action?.enum || [];
  const paramRows = extractParamRows(tool);
  const securityLevel = tool.securityLevel || 'unknown';

  const lines = [];
  lines.push(`# ${tool.name}`);
  lines.push('');
  lines.push(`> ${tool.description || '(no description)'}`);
  lines.push('');
  lines.push('| Property | Value |');
  lines.push('|------|-----|');
  lines.push(`| Layer | ${layer} |`);
  lines.push(`| Safety level | ${securityLevel} |`);
  lines.push(`| Needs Godot | ${tool.needsGodot ? 'yes' : 'no'} |`);
  lines.push(`| Needs editor | ${tool.needsEditor ? 'yes' : 'no'} |`);
  lines.push(`| Read-only | ${tool.readonly ? 'yes' : 'no'} |`);
  lines.push(`| Long-running | ${tool.longRunning ? 'yes' : 'no'} |`);
  lines.push('');

  if (actions.length > 0) {
    lines.push('## Actions');
    lines.push('');
    for (const a of actions) lines.push(`- \`${a}\``);
    lines.push('');
  }

  if (paramRows.length > 0) {
    lines.push('## Parameters');
    lines.push('');
    lines.push('| Parameter | Type | Required | Description |');
    lines.push('|------|------|------|------|');
    for (const r of paramRows) {
      lines.push(`| \`${r.name}\` | ${r.type} | ${r.required} | ${r.description || ''} |`);
    }
    lines.push('');
  }

  if (tool.riskDistribution) {
    lines.push('## Risk breakdown');
    lines.push('');
    const rd = tool.riskDistribution;
    const parts = [];
    if (rd.read) parts.push(`read ${rd.read}`);
    if (rd.write) parts.push(`write ${rd.write}`);
    if (rd.destructive) parts.push(`destructive ${rd.destructive}`);
    if (rd.process) parts.push(`process ${rd.process}`);
    lines.push(parts.length > 0 ? parts.join(' / ') : 'no risk data');
    lines.push('');
  }

  lines.push('---');
  lines.push(`<!-- AUTO-GENERATED by scripts/gen-tool-docs.mjs from capability-matrix.json v${matrixVersion}. DO NOT edit manually; re-run npm run gen:tool-docs after tool changes. -->`);
  lines.push('');

  return lines.join('\n');
}

// ═══════════════════════════════════════════════════════════════════════════════
// IO 层 main(写文件)
// ═══════════════════════════════════════════════════════════════════════════════

function main() {
  if (!existsSync(MATRIX_PATH)) {
    console.error(`[gen-tool-docs] capability-matrix.json 不存在: ${MATRIX_PATH}`);
    console.error('  先跑 npm run build-matrix 生成。');
    process.exit(1);
  }
  const matrix = JSON.parse(readFileSync(MATRIX_PATH, 'utf-8'));
  const version = matrix.version || 'unknown';
  const tools = matrix.tools || [];
  if (tools.length === 0) {
    console.error('[gen-tool-docs] matrix.tools 为空,中止(防覆盖空目录)');
    process.exit(1);
  }

  // 清空旧生成文件(保留手写的 help.md / load_skill.md 等非 AUTO-GENERATED 文件)
  mkdirSync(OUT_DIR, { recursive: true });
  let removed = 0;
  for (const f of readdirSync(OUT_DIR)) {
    if (!f.endsWith('.md')) continue;
    const content = readFileSync(join(OUT_DIR, f), 'utf-8');
    if (content.includes('AUTO-GENERATED by scripts/gen-tool-docs.mjs')) {
      rmSync(join(OUT_DIR, f));
      removed++;
    }
  }

  // 生成
  let generated = 0;
  for (const tool of tools) {
    const md = generateToolDoc(tool, version);
    writeFileSync(join(OUT_DIR, `${tool.name}.md`), md, 'utf-8');
    generated++;
  }
  console.log(`[gen-tool-docs] 生成 ${generated} 文件 → docs/tools/ (清理 ${removed} 旧生成文件, matrix v${version})`);
}

// 仅在直接执行时跑 main(import 时不跑,供测试)
const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isDirectRun) {
  main();
}
